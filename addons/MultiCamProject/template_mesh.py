def _mesh(name, part):
    me = bpy.data.meshes.new(name)
    me.from_pydata([tuple(v) for v in part["verts"]], [], [tuple(f) for f in part["faces"]])
    uv = me.uv_layers.new(name="UVMap").data
    for loop, co in zip(range(len(me.loops)), (c for face in part["uvs"] for c in face)):
        uv[loop].uv = co
    seams = {frozenset(e) for e in part["seams"]}
    for e in me.edges:
        e.use_seam = frozenset(e.vertices) in seams
    me.shade_smooth()
    me.validate()
    return me


def ensure(scene):
    """The ROOM_Template collection in the scene, with every part no object is named after.
    Returns the names of the objects made."""
    coll = bpy.data.collections.get(NAME)
    if coll is None:
        coll = bpy.data.collections.new(NAME)
    if coll not in scene.collection.children_recursive:
        scene.collection.children.link(coll)
    made = []
    for name, part in PARTS.items():
        if name in bpy.data.objects:
            continue
        obj = bpy.data.objects.new(name, _mesh(name, part))
        coll.objects.link(obj)
        made.append(name)
    return made
