def ensure(scene):
    """Make NAME in the scene's top collection when the file has no object of that name.
    Returns the object made, else None."""
    if NAME in bpy.data.objects:
        return None
    me = bpy.data.meshes.new(NAME)
    me.from_pydata([tuple(v) for v in VERTS], [], [tuple(f) for f in FACES])
    uv = me.uv_layers.new(name="UVMap").data
    for loop, co in zip(range(len(me.loops)), (c for face in UVS for c in face)):
        uv[loop].uv = co
    seams = {frozenset(e) for e in SEAMS}
    for e in me.edges:
        e.use_seam = frozenset(e.vertices) in seams
    me.shade_smooth()
    me.validate()
    obj = bpy.data.objects.new(NAME, me)
    scene.collection.objects.link(obj)
    return obj
